#!/usr/bin/env python3
"""Lift the raw SPURS job binaries captured with SPU_DUMP_MISS into out/port/spu.

Run from the project root:
    py tools/prepare_spurs_jobs.py

Reads out/spu-misses/spujob_<FP>_<SIZE>.bin (game-derived, gitignored), lifts
each as a position-independent job image loaded at LS 0 and entered at LS 0
(the job CRT), and writes out/port/spu/jobs_register.c, which registers each
lifted entry by FNV-1a-64 fingerprint (what spu_workload_dispatch_job looks up).
Nothing is written into ../ps3recomp. Output is game-derived: DO NOT COMMIT.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# (fingerprint, size, symbol prefix, image id). 1 = fob_spu, 2 = fob_policy.
JOBS = (
    (0x054414E2CCD626FF, 1040, "fobjob0544_", 3, None),
    (0x64D9D14299A2B7AB, 272, "fobjob64D9_", 4, None),
)
BOOT_JOBS = (
    (0x8927C5C0BC233071, 2192, "fobjob8927_", 6, None),
    (0xA3A153B14368B1B7, 7696, "fobjobA3A1_", 7, None),
    # The float table after this boundary is loaded into LS as data.
    (0xB5EFEE742877FBAD, 32800, "fobjobB5EF_", 8, 0x5C10),
)
LATER_BOOT_JOBS = (
    (0x6F43025331D3AA1A, 7184, "fobjob6F43_", 9, None),
)


def fp_fnv(data: bytes) -> int:
    h = 1469598103934665603
    for value in data:
        h = ((h ^ value) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def run(args: list[str]) -> None:
    print("+", " ".join(args), flush=True)
    subprocess.run(args, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--boot-dumps", type=Path,
                        help="Capture directory containing the three additional boot jobs.")
    parser.add_argument("--later-dumps", type=Path,
                        help="Capture directory containing the later boot job.")
    args = parser.parse_args()
    if args.later_dumps is not None and args.boot_dumps is None:
        parser.error("--later-dumps requires --boot-dumps")
    root = Path(__file__).resolve().parent.parent
    tools = root.parent / "ps3recomp" / "tools"
    spu_dir = root / "out/port/spu"
    reg = spu_dir / "jobs_register.c"
    if not (spu_dir / "fob_spu" / "spu_recomp.c").exists():
        raise SystemExit("ERRO: rode prepare_spu_elf.py antes (out/port/spu/fob_spu ausente).")
    for tool in ("spu_lifter.py", "wrap_spu_elf.py"):
        if not (tools / tool).is_file():
            raise SystemExit("ERRO: ferramenta ausente: " + str(tools / tool))

    entries = []
    with tempfile.TemporaryDirectory(prefix="fob-jobs-", dir=root / "out") as td:
        stage = Path(td)
        jobs = [(root / "out/spu-misses", job) for job in JOBS]
        if args.boot_dumps is not None:
            jobs.extend((args.boot_dumps, job) for job in BOOT_JOBS)
        if args.later_dumps is not None:
            jobs.extend((args.later_dumps, job) for job in LATER_BOOT_JOBS)
        for dump_dir, (fp, size, prefix, image_id, code_end) in jobs:
            raw_path = dump_dir / f"spujob_{fp:016X}_{size}.bin"
            if not raw_path.is_file():
                raise SystemExit("ERRO: dump ausente (rode com SPU_DUMP_MISS): " + str(raw_path))
            data = raw_path.read_bytes()
            if len(data) != size or fp_fnv(data) != fp:
                raise SystemExit(f"ERRO: tamanho/fingerprint de {raw_path.name} não confere.")
            name = f"fob_job_{fp:016X}"
            elf = stage / (name + ".elf")
            out = stage / name
            report = stage / (name + ".json")
            run([sys.executable, str(tools / "wrap_spu_elf.py"), str(raw_path),
                 "--entry", "0x0", "--base", "0x0", "--out", str(elf)])
            lift = [sys.executable, str(tools / "spu_lifter.py"), "--auto-functions", str(elf),
                    "--base", "0x0", "--symbol-prefix", prefix,
                    "--output", str(out), "--report", str(report)]
            if code_end is not None:
                lift.extend(["--code-end", hex(code_end)])
            run(lift)
            diag = json.loads(report.read_text(encoding="utf-8"))
            starts = {s for s, _ in diag.get("functions", [])}
            missing = (set(diag.get("call_targets", [])) | set(diag.get("branch_targets", []))) - starts
            if diag.get("unsupported") or missing or 0 not in starts:
                raise SystemExit(f"ERRO: lift incompleto em {name}: unsupported="
                                 f"{diag.get('unsupported')!r} missing={sorted(map(hex, missing))}")
            entries.append((fp, prefix, image_id, name))

        lines = ["/* GENERATED by tools/prepare_spurs_jobs.py -- game-derived, DO NOT COMMIT.",
                 " * Registers lifted SPURS job images by fingerprint (job entry = LS 0). */",
                 '#include "spu_workload.h"',
                 "extern void spu_begin_image(int image_id);"]
        for fp, prefix, image_id, name in entries:
            lines.append(f"extern void {prefix}spu_func_00000000(spu_context*);")
            lines.append(f"extern void {prefix}spu_recomp_register(void);")
        lines += ["", "__attribute__((constructor))", "static void fob_jobs_register_ctor(void)", "{"]
        for fp, prefix, image_id, name in entries:
            lines += [f"    spu_begin_image({image_id}); {prefix}spu_recomp_register();",
                      f"    spu_workload_register_img(0x{fp:016X}ULL, {prefix}spu_func_00000000,"
                      f" {image_id}, \"{name}\");"]
        lines += ["    spu_begin_image(0);", "}", ""]

        for fp, prefix, image_id, name in entries:
            dst = spu_dir / name
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(stage / name, dst)
        reg.write_text("\n".join(lines), encoding="utf-8")
    print("\nSUCESSO:", len(entries), "jobs liftados e registrados em", reg)
    print("PRÓXIMO: acrescente jobs_register.c à lista do foreach em out/port/CMakeLists.txt e recompile.")


if __name__ == "__main__":
    main()
